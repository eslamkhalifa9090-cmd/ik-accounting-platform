out.append(f"UPDATE courses SET subtitle = {q(subtitle)}, intro = {q(intro)}, audience = {q(audience)} WHERE slug = {q(SLUG)};")
for i, (title, topics, teaser) in enumerate(levels, 1):
    out.append("INSERT OR IGNORE INTO levels (course_id, num, title, topics, teaser) "
               f"SELECT id, {i}, {q(title)}, {q(topics)}, {q(teaser)} FROM courses WHERE slug = {q(SLUG)};")
    out.append("INSERT OR IGNORE INTO exams (course_id, kind, after_level, title, question_count, pass_pct, duration_min) "
               f"SELECT id, 'level', {i}, {q('امتحان المستوى ' + str(i))}, 10, 50, 15 FROM courses WHERE slug = {q(SLUG)};")
for after, title in [(3, "الامتحان التراكمي الأول (المستويات 1 إلى 3)"), (7, "الامتحان الشامل (المستويات 1 إلى 7)")]:
    out.append("INSERT OR IGNORE INTO exams (course_id, kind, after_level, title, question_count, pass_pct, duration_min) "
               f"SELECT id, 'cumulative', {after}, {q(title)}, 20, 50, 40 FROM courses WHERE slug = {q(SLUG)};")

# أسئلة المستوى الأول من ملف الإكسيل (نفس أعمدة لصق الأدمن)، ومابتتكررش لو الملف اتنفذ تاني
# أسئلة الصح والغلط ليها اختيارين بس، فالخانات الفاضية بتتشال
ws = load_workbook(sys.argv[1])["أسئلة المنصة"]
n = 0
for row in ws.iter_rows(min_row=2, values_only=True):
    if not row[0]:
        continue
    body, opts, ans, expl = row[0], [o for o in row[1:5] if o not in (None, "")], int(row[5]), row[6]
    assert 2 <= len(opts) <= 4 and 1 <= ans <= len(opts), body
    exam = f"(SELECT e.id FROM exams e JOIN courses c ON c.id = e.course_id WHERE c.slug = {q(SLUG)} AND e.kind = 'level' AND e.after_level = 1)"
    out.append("INSERT INTO questions (exam_id, body, options, answer, explanation) "
               f"SELECT {exam}, {q(body)}, {q(json.dumps(opts, ensure_ascii=False, separators=(",", ":")))}, {ans - 1}, {q(expl)} "
               f"WHERE NOT EXISTS (SELECT 1 FROM questions WHERE exam_id = {exam} AND body = {q(body)});")
    n += 1

path = pathlib.Path(__file__).resolve().parent.parent / "migrations" / "0006_tax.sql"
path.write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", path, n, "questions")
